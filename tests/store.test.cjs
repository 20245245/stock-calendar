'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const Store=require('../store.js'),root=path.resolve(__dirname,'..');
const payload=JSON.parse(fs.readFileSync(path.join(root,'data/calendar.json'),'utf8'));
const old=JSON.parse(fs.readFileSync(path.join(root,'data/legacy-baseline.json'),'utf8'));
const ctx=vm.createContext({document:{getElementById:()=>({})},Date,Map,Set,CalendarStore:Store});
vm.runInContext(fs.readFileSync(path.join(root,'calendar-data.js'),'utf8'),ctx);
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
vm.runInContext(app.slice(0,app.indexOf('let catalog = normalize(CALENDAR_DATA);')),ctx);
const normalize=input=>{ctx.testInput=input;return JSON.parse(vm.runInContext('JSON.stringify(normalize(testInput))',ctx));};
const catalog=normalize(payload.events),flat=Store.flat(catalog);
assert.equal(flat.length,154);assert.equal(new Set(flat.map(x=>x.event.id)).size,154);
assert.equal(flat.filter(x=>x.event.priority==='core'&&x.event.status==='confirmed'&&!x.event.archived).length,30);
const state=Store.empty(),target=flat.find(x=>x.event.text==='미국 10월 CPI');
Store.save(catalog,state,target.date,target.event,'CPI 발표 후 확인할 메모');
assert.equal(Object.keys(state.overrides).length,0);
assert.equal(state.notes[target.event.id],'CPI 발표 후 확인할 메모');
const next=structuredClone(catalog),moved=next.find(d=>d.date===target.date).events.find(e=>e.id===target.event.id);
moved.time='23:30';
assert.equal(Store.flat(Store.build(next,state)).find(x=>x.event.id===target.event.id).event.time,'23:30');
assert.equal(state.notes[target.event.id],'CPI 발표 후 확인할 메모');
const edited={...target.event,text:'내가 바꾼 CPI 제목'};
Store.save(catalog,state,target.date,edited,'메모 유지');
assert.equal(Store.flat(Store.build(next,state)).find(x=>x.event.id===target.event.id).event.text,'내가 바꾼 CPI 제목');
Store.restore(state,target.event.id);
assert.equal(Store.flat(Store.build(next,state)).find(x=>x.event.id===target.event.id).event.time,'23:30');
assert.equal(state.notes[target.event.id],'메모 유지');
Store.remove(catalog,state,target.event.id);
assert(!Store.flat(Store.build(next,state)).some(x=>x.event.id===target.event.id));
Store.restore(state,target.event.id);
Store.save(catalog,state,'2026-11-12',{id:'my-event',type:'event',text:'내 일정',status:'unconfirmed',priority:'watch'},'개인 메모');
assert(Store.flat(Store.build(next,state)).some(x=>x.event.id==='my-event'&&x.event.localOnly));
const checked=Store.validate(JSON.parse(JSON.stringify(state)),normalize);
assert.equal(checked.notes['my-event'],'개인 메모');
const migration=Store.migrate(normalize(old),normalize(old),catalog);
assert.equal(Object.keys(migration.overrides).length,0);
assert.equal(Object.keys(migration.custom).length,0);
const changedOld=structuredClone(old);changedOld[0].events[0].note+=' 사용자 메모';
const changed=Store.migrate(normalize(changedOld),normalize(old),catalog);
assert.equal(Object.keys(changed.overrides).length,1);
const merged=Store.mergePrivate(checked,changed);
assert.equal(merged.notes['my-event'],'개인 메모');
assert.equal(Object.keys(merged.overrides).length,1);
const fallback=JSON.parse(vm.runInContext('JSON.stringify(CALENDAR_DATA)',ctx));
assert.deepEqual(fallback,payload.events);
assert.equal(JSON.parse(JSON.stringify(state)).events,undefined);
const invalid=JSON.parse('{"schema":3,"custom":{},"overrides":{},"hidden":[],"notes":{"__proto__":"bad"}}');
assert.throws(()=>Store.validate(invalid,normalize));
console.log('PASS: public updates, private notes/custom edits, restore/hide, legacy migration, backup validation, fallback parity (154 events)');
